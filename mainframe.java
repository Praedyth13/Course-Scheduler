    private void dropStudentButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_dropStudentButtonActionPerformed
        ArrayList<String> semesters = SemesterQueries.getSemesterList();
        StudentEntry student = (StudentEntry) studentComboBox3.getSelectedItem();
        String ID = student.getStudentID();

        String line = String.format("%s%s%s", "Student ", student, " has been removed from the list of students.\n");
        dropStudentTextArea.append(line);

        for(String semester: semesters){
            ArrayList<ScheduleEntry> courses = ScheduleQueries.getScheduleByStudent(semester, ID);
            line = String.format("%s%s", "\nFor Semester: ", semester);
            dropStudentTextArea.append(line);

            for(ScheduleEntry course: courses){
                String code = course.getCourseCode();
                ScheduleQueries.dropStudentScheduleByCourse(semester, code, ID);

                if(course.getStatus().equals("S")){
                    line = String.format("%s%s%s%s", student, "has been dropped from ", code, "\n");
                    dropStudentTextArea.append(line);

                    ArrayList<StudentEntry> waitlisted = MultiTableQueries.getWaitlistedStudentsByClass(semester, code);
                    if(!waitlisted.isEmpty()){
                        String newID = waitlisted.get(0).getStudentID();
                        java.sql.Timestamp Timestamp = new java.sql.Timestamp(Calendar.getInstance().getTime().getTime());
                        ScheduleEntry update = new ScheduleEntry(semester, code, newID, "S", Timestamp);
                        ScheduleQueries.updateScheduleEntry(update);
                        line = String.format("%s%s%s%s", waitlisted.get(0), "has been scheduled into ", code, "\n");
                        dropStudentTextArea.append(line);
                    }
                }

                else{
                    line = String.format("%s%s%s%s", student, "has been dropped from the waitlist for ", code, "\n");
                    dropStudentTextArea.append(line);
                }
            }
        }
        StudentQueries.dropStudent(ID);
        rebuildStudentComboBoxes();
    }//GEN-LAST:event_dropStudentButtonActionPerformed

    private void checkData() {
        try {
            FileReader reader = new FileReader("xzq789yy.txt");
            BufferedReader breader = new BufferedReader(reader);

            String encodedAuthor = breader.readLine();
            String encodedProject = breader.readLine();
            byte[] decodedAuthor = Base64.getDecoder().decode(encodedAuthor);
            author = new String(decodedAuthor);
            byte[] decodedProject = Base64.getDecoder().decode(encodedProject);
            project = new String(decodedProject);
            reader.close();

        } catch (FileNotFoundException e) {
            //get user info and create file
            author = JOptionPane.showInputDialog("Enter your first and last name.");
            project = "Course Scheduler Fall 2024";

            //write data to the data file.
            try {
                FileWriter writer = new FileWriter("xzq789yy.txt", true);
                BufferedWriter bufferedWriter = new BufferedWriter(writer);

                // encode the output data.
                String encodedAuthor = Base64.getEncoder().encodeToString(author.getBytes());

                bufferedWriter.write(encodedAuthor);
                bufferedWriter.newLine();

                String encodedProject = Base64.getEncoder().encodeToString(project.getBytes());
                bufferedWriter.write(encodedProject);

                bufferedWriter.close();
            } catch (IOException ioe) {
                ioe.printStackTrace();
                System.exit(1);
            }

        } catch (IOException e) {
            e.printStackTrace();
            System.exit(1);
        }

    }

