    private void dropClassButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_dropClassButton2ActionPerformed
        String semester = currentSemesterLabel.getText();
        StudentEntry student = (StudentEntry) studentComboBox4.getSelectedItem();
        String code = (String) classComboBox1.getSelectedItem();
        String ID = student.getStudentID();
        int classSeats = ClassQueries.getClassSeats(semester, code);
        
        ScheduleQueries.dropStudentScheduleByCourse(semester, code, ID);
        int takenSeats = ScheduleQueries.getScheduledStudentCount(semester, code);
        int openSeats = classSeats - takenSeats;
        ArrayList<StudentEntry> waitlisted = MultiTableQueries.getWaitlistedStudentsByClass(semester, code);
        if(!waitlisted.isEmpty() && openSeats != 0){
            String newID = waitlisted.get(0).getStudentID();
            java.sql.Timestamp Timestamp = new java.sql.Timestamp(Calendar.getInstance().getTime().getTime());
            ScheduleEntry update = new ScheduleEntry(semester, code, newID, "S", Timestamp);
            ScheduleQueries.updateScheduleEntry(update);
            String line = String.format("%s%s%s\n%s%s%s", 
                                        student, " has been dropped from ", code,
                                        waitlisted.get(0), "has been scheduled into ", code);
            dropClassTextArea2.setText(line);
        }
        else{
            String line = String.format("%s%s%s", student, " has been dropped from ", code);
            dropClassTextArea2.setText(line);
        }
        
    }//GEN-LAST:event_dropClassButton2ActionPerformed

